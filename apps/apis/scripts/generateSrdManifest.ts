import { brotliCompressSync, constants } from 'node:zlib'
import { writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { auditSrdSourceSemantics } from '../../../packages/source-data/src/srd/audit.js'
import { prepareSrdImport } from '../../../packages/source-data/src/srd/import.js'
import { canonicalizeRuleDocument } from '@artificer-toolkit/shared/rules'

const issues = auditSrdSourceSemantics()
if (issues.length)
  throw new Error(`Canonical SRD semantic audit failed: ${issues.length} issue(s).`)

const payload = brotliCompressSync(Buffer.from(canonicalizeRuleDocument(prepareSrdImport())), {
  params: { [constants.BROTLI_PARAM_QUALITY]: 11 }
}).toString('base64')
const output = `// Generated by apps/apis/scripts/generateSrdManifest.ts. Do not edit.\nexport const srdManifestBrotliBase64 =\n  '${payload}'\n`

await writeFile(resolve(import.meta.dirname, '../convex/content/srdManifest.generated.ts'), output)
