/**
 * Stable deterministic UUIDs for all SRD subject entities.
 *
 * Format: 00000000-0000-0000-DDDD-NNNN00000000
 *   DDDD = domain code (encoded in clock_seq_hi)
 *   NNNN = 1-based index within domain (hex)
 *
 * Domain codes:
 *   0010 = class (parent classes)
 *   0011 = subclass
 *   0020 = spell
 *   0030 = race
 *   0031 = subrace
 *   0040 = background
 *   0050 = feat (subject)
 *   0060 = equipment
 *   0070 = creature (SRD monsters)
 *   0080 = vehicle (PHB vehicles)
 */

function subjectId(domain: string, index: number): string {
  const hex = index.toString(16).padStart(4, '0')
  return `00000000-0000-0000-${domain}-${hex}00000000`
}

