import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const entries = require('subtlex-word-frequencies')

// Two- and three-letter tokens in the corpus include subtitle fragments, so they need a frequency floor.
const shortWordMinimumCount = 1000

const words = [
  ...new Set(
    entries
      .filter(
        ({ word, count }) =>
          /^[A-Za-z]{4,}$/.test(word) ||
          (/^[A-Za-z]{2,3}$/.test(word) && count >= shortWordMinimumCount)
      )
      .map(({ word }) => word.toLowerCase())
  )
].sort()

writeFileSync(
  new URL('../src/domains/account/usernameWordList.ts', import.meta.url),
  `// Generated by \`yarn workspace @artificer-toolkit/shared generate:username-words\` from
// subtlex-word-frequencies@2.0.0 (ISC): lowercase words of four or more letters, plus two- and
// three-letter words seen at least ${shortWordMinimumCount} times. Server-only data
// for the Q22 compound username check; do not import it from code the web bundle reaches.
export const usernameWordList = '${words.join(' ')}'
`
)
console.log(`Wrote ${words.length} words`)
