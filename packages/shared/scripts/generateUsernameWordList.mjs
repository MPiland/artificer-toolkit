import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const entries = require('subtlex-word-frequencies')

const words = [
  ...new Set(entries.map(({ word }) => word.toLowerCase()).filter((word) => /^[a-z]{4,}$/.test(word)))
].sort()

writeFileSync(
  new URL('../src/domains/account/usernameWordList.ts', import.meta.url),
  `// Generated by \`yarn workspace @artificer-toolkit/shared generate:username-words\` from
// subtlex-word-frequencies@2.0.0 (ISC): lowercase words of four or more letters. Server-only data
// for the Q22 compound username check; do not import it from code the web bundle reaches.
export const usernameWordList = '${words.join(' ')}'
`
)
console.log(`Wrote ${words.length} words`)
